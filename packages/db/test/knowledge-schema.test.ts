import { afterAll, beforeAll, describe, expect, it } from "vitest";
import pg from "pg";
import { sql } from "drizzle-orm";
import { createDb, schema, withContext, type Db } from "../src/index.ts";

// AI Studio knowledge base slice 1: sources and chunks are tenant isolated, role scoped (members read, owner/admin write), and guarded.
const NAME = process.env.CRM_DB_NAME ?? "crm";
const url = (u: string, p: string) => `postgres://${u}:${p}@127.0.0.1:5436/${NAME}`;
const run = Date.now().toString(36);
const U = { owner: `kb-owner-${run}`, admin: `kb-admin-${run}`, agent: `kb-agent-${run}`, viewer: `kb-viewer-${run}`, ownerB: `kb-ownerb-${run}` };
let app: Db, worker: Db, root: pg.Client;
let A = "", B = "", srcA = "", srcB = "";
const ctx = (userId?: string, workspaceId?: string) => ({ userId, workspaceId });
const q = <T = Record<string, unknown>>(db: Db, c: ReturnType<typeof ctx>, s: ReturnType<typeof sql>) => withContext(db, c, async (tx) => (await tx.execute(s)).rows as T[]);
const rejects = (p: Promise<unknown>, re: RegExp) => expect(p).rejects.toMatchObject({ cause: { message: expect.stringMatching(re) } });
const RLS = /row-level security/;
const addSource = (c: ReturnType<typeof ctx>, ws: string, by = c.userId!, title = "S") => withContext(app, c, async (tx) => (await tx.insert(schema.knowledgeSources).values({ workspaceId: ws, type: "text", title, status: "ready", createdBy: by }).returning({ id: schema.knowledgeSources.id }))[0]!.id);

beforeAll(async () => {
  root = new pg.Client({ connectionString: process.env.DATABASE_URL_ADMIN ?? url("postgres", "postgres") });
  await root.connect();
  app = createDb(url("crm_app", "app_dev")); worker = createDb(url("crm_worker", "worker_dev"));
  for (const id of Object.values(U)) await root.query(`INSERT INTO "user"(id,name,email,email_verified) VALUES ($1,$1,$2,true) ON CONFLICT (id) DO NOTHING`, [id, `${id}@t.test`]);
  const mk = (owner: string, slug: string) => withContext(app, { userId: owner }, async (tx) => {
    const [w] = await tx.insert(schema.workspaces).values({ name: slug, slug, ownerUserId: owner }).returning();
    await tx.insert(schema.memberships).values({ workspaceId: w!.id, userId: owner, role: "owner" });
    return w!.id;
  });
  A = await mk(U.owner, `kb-a-${run}`); B = await mk(U.ownerB, `kb-b-${run}`);
  await withContext(app, ctx(U.owner, A), (tx) => tx.insert(schema.memberships).values([{ workspaceId: A, userId: U.admin, role: "admin" }, { workspaceId: A, userId: U.agent, role: "agent" }, { workspaceId: A, userId: U.viewer, role: "viewer" }]));
  srcA = await addSource(ctx(U.owner, A), A);
  srcB = await addSource(ctx(U.ownerB, B), B);
  await withContext(app, ctx(U.owner, A), (tx) => tx.insert(schema.knowledgeChunks).values({ workspaceId: A, sourceId: srcA, position: 0, content: "Refunds are paid within fourteen days.", tokenEstimate: 10 }));
  await withContext(app, ctx(U.ownerB, B), (tx) => tx.insert(schema.knowledgeChunks).values({ workspaceId: B, sourceId: srcB, position: 0, content: "Refunds in workspace B take a month.", tokenEstimate: 10 }));
});
afterAll(async () => { await Promise.all([app.$client.end(), worker.$client.end(), root.end()]); });

describe("tenant isolation and roles", () => {
  it("every member reads their workspace's sources and chunks; outsiders and context-less sessions see nothing", async () => {
    for (const u of [U.owner, U.admin, U.agent, U.viewer]) {
      expect(await q(app, ctx(u, A), sql`SELECT id FROM knowledge_sources`)).toHaveLength(1);
      expect(await q(app, ctx(u, A), sql`SELECT id FROM knowledge_chunks`)).toHaveLength(1);
    }
    expect(await q(app, ctx(U.ownerB, A), sql`SELECT id FROM knowledge_sources`)).toEqual([]);
    expect(await q(app, ctx(U.ownerB, A), sql`SELECT id FROM knowledge_chunks`)).toEqual([]);
    expect(await q(app, ctx(U.ownerB, B), sql`SELECT id FROM knowledge_chunks WHERE workspace_id = ${A}::uuid`)).toEqual([]);
    expect(await q(app, ctx(U.owner), sql`SELECT id FROM knowledge_chunks`)).toEqual([]);
  });
  it("full-text search is generated by the database and never crosses workspaces", async () => {
    const hits = (u: string, ws: string) => q<{ content: string }>(app, ctx(u, ws), sql`SELECT content FROM knowledge_chunks WHERE tsv @@ websearch_to_tsquery('simple', 'refunds')`);
    expect((await hits(U.owner, A)).map((r) => r.content)).toEqual(["Refunds are paid within fourteen days."]);
    expect((await hits(U.ownerB, B)).map((r) => r.content)).toEqual(["Refunds in workspace B take a month."]);
    expect(await hits(U.ownerB, A)).toEqual([]);
  });
  it("only owner and admin write; agents and viewers cannot", async () => {
    await addSource(ctx(U.admin, A), A);
    for (const u of [U.agent, U.viewer]) {
      await rejects(addSource(ctx(u, A), A), RLS);
      await rejects(withContext(app, ctx(u, A), (tx) => tx.insert(schema.knowledgeChunks).values({ workspaceId: A, sourceId: srcA, position: 9, content: "x", tokenEstimate: 1 })), RLS);
      expect(await withContext(app, ctx(u, A), (tx) => tx.execute(sql`UPDATE knowledge_sources SET title = 'hacked' WHERE id = ${srcA}::uuid RETURNING id`)).then((r) => r.rows)).toEqual([]);
      expect(await withContext(app, ctx(u, A), (tx) => tx.execute(sql`DELETE FROM knowledge_chunks WHERE source_id = ${srcA}::uuid RETURNING id`)).then((r) => r.rows)).toEqual([]);
    }
  });
  it("cannot write into another workspace, or create a source in the name of someone else", async () => {
    await rejects(addSource(ctx(U.owner, A), B), RLS);
    await rejects(addSource(ctx(U.owner, A), A, U.admin), RLS);
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.insert(schema.knowledgeChunks).values({ workspaceId: B, sourceId: srcB, position: 5, content: "x", tokenEstimate: 1 })), RLS);
  });
  it("a chunk cannot point at a source of another workspace (composite foreign key)", async () => {
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.insert(schema.knowledgeChunks).values({ workspaceId: A, sourceId: srcB, position: 7, content: "x", tokenEstimate: 1 })), /foreign key/);
  });
  it("an owner of A cannot update or delete B's rows", async () => {
    expect(await q(app, ctx(U.owner, A), sql`UPDATE knowledge_sources SET title = 'x' WHERE id = ${srcB}::uuid RETURNING id`)).toEqual([]);
    expect(await q(app, ctx(U.owner, A), sql`DELETE FROM knowledge_chunks WHERE source_id = ${srcB}::uuid RETURNING id`)).toEqual([]);
  });
});

describe("guards", () => {
  it("sources are never hard-deleted by the app role, and the worker role has no access in this slice", async () => {
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.execute(sql`DELETE FROM knowledge_sources WHERE id = ${srcA}::uuid`)), /permission denied/);
    await rejects(q(worker, ctx(U.owner, A), sql`SELECT id FROM knowledge_sources`), /permission denied/);
    await rejects(q(worker, ctx(U.owner, A), sql`SELECT id FROM knowledge_chunks`), /permission denied/);
  });
  it("identity columns cannot be updated; a deleted source is final", async () => {
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.execute(sql`UPDATE knowledge_sources SET type = 'url' WHERE id = ${srcA}::uuid`)), /permission denied/);
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.execute(sql`UPDATE knowledge_sources SET workspace_id = ${B}::uuid WHERE id = ${srcA}::uuid`)), /permission denied/);
    const s = await addSource(ctx(U.owner, A), A, U.owner, "to delete");
    await withContext(app, ctx(U.owner, A), (tx) => tx.execute(sql`UPDATE knowledge_sources SET deleted_at = now() WHERE id = ${s}::uuid`));
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.execute(sql`UPDATE knowledge_sources SET deleted_at = NULL WHERE id = ${s}::uuid`)), /final/);
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.execute(sql`UPDATE knowledge_sources SET title = 'again' WHERE id = ${s}::uuid`)), /final/);
  });
  it("chunks are immutable for the app role (re-index = delete + insert) and the table checks hold", async () => {
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.execute(sql`UPDATE knowledge_chunks SET content = 'x' WHERE source_id = ${srcA}::uuid`)), /permission denied/);
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.insert(schema.knowledgeChunks).values({ workspaceId: A, sourceId: srcA, position: 0, content: "dup position", tokenEstimate: 1 })), /unique/);
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.insert(schema.knowledgeChunks).values({ workspaceId: A, sourceId: srcA, position: 3, content: "", tokenEstimate: 1 })), /knowledge_chunks_content/);
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.insert(schema.knowledgeChunks).values({ workspaceId: A, sourceId: srcA, position: 4, content: "x".repeat(2001), tokenEstimate: 1 })), /knowledge_chunks_content/);
    await rejects(withContext(app, ctx(U.owner, A), (tx) => tx.execute(sql`UPDATE knowledge_sources SET error = 'Some free text with spaces' WHERE id = ${srcA}::uuid`)), /knowledge_sources_error/);
  });
  it("the GIN index backs the search", async () => {
    const r = await root.query(`SELECT indexdef FROM pg_indexes WHERE tablename = 'knowledge_chunks' AND indexname = 'knowledge_chunks_tsv_idx'`);
    expect(r.rows[0].indexdef).toMatch(/USING gin \(tsv\)/);
  });
});
