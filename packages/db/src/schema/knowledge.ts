import { sql } from "drizzle-orm";
import { customType, integer, pgTable, text, timestamp, uuid } from "drizzle-orm/pg-core";
import { workspaces } from "./tenancy.ts";

// Hand-written migration 0031 is the source of truth (checks, RLS, guard); these definitions only type the columns.
const id = () => uuid("id").primaryKey().default(sql`uuidv7()`);
const workspaceId = () => uuid("workspace_id").notNull().references(() => workspaces.id);
const ts = (n: string) => timestamp(n, { withTimezone: true });
const tsvector = customType<{ data: string }>({ dataType: () => "tsvector" });

export const KNOWLEDGE_SOURCE_TYPES = ["text", "url", "file"] as const;
export const KNOWLEDGE_SOURCE_STATUSES = ["pending", "ready", "failed"] as const;

export const knowledgeSources = pgTable("knowledge_sources", {
  id: id(),
  workspaceId: workspaceId(),
  type: text("type").notNull(),
  title: text("title").notNull(),
  /** URL for type url, file name for type file, null for pasted text. */
  sourceRef: text("source_ref"),
  status: text("status").notNull().default("pending"),
  /** Failure code, never a message that could carry content. */
  error: text("error"),
  /** Normalised text kept so text and file sources can be re-chunked; never returned by list endpoints. */
  body: text("body"),
  charCount: integer("char_count").notNull().default(0),
  chunkCount: integer("chunk_count").notNull().default(0),
  createdBy: text("created_by"),
  createdAt: ts("created_at").notNull().defaultNow(),
  updatedAt: ts("updated_at").notNull().defaultNow(),
  deletedAt: ts("deleted_at"),
});

export const knowledgeChunks = pgTable("knowledge_chunks", {
  id: id(),
  workspaceId: workspaceId(),
  sourceId: uuid("source_id").notNull(),
  position: integer("position").notNull(),
  content: text("content").notNull(),
  /** to_tsvector('simple', content), generated by the database. */
  tsv: tsvector("tsv").generatedAlwaysAs(sql`to_tsvector('simple', content)`),
  tokenEstimate: integer("token_estimate").notNull(),
  createdAt: ts("created_at").notNull().defaultNow(),
});
